export type ArticleCard = Pick<
	Article,
	'slug' | 'title' | 'description' | 'category' | 'published' | 'updated' | 'readingTime'
>;

export const toArticleCard = (article: Article): ArticleCard => ({
	slug: article.slug,
	title: article.title,
	description: article.description,
	category: article.category,
	published: article.published,
	updated: article.updated,
	readingTime: article.readingTime
});

export const getArticle = (slug: string) => articles.find((article) => article.slug === slug);

export const getArticlesByCategory = (categorySlug: string) =>
	articles.filter((article) => article.category === categorySlug);

/** Карточки для списков (/stati, категории, карта) — без тел статей. */
export const getArticleCards = (): ArticleCard[] => articles.map(toArticleCard);

export const getArticleCardsByCategory = (categorySlug: string): ArticleCard[] =>
	getArticlesByCategory(categorySlug).map(toArticleCard);
